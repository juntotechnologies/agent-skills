"""Pure renderers: the site-taste data in, Markdown out."""
from taste_model import Area, Evidence, FileRef, Principle, Site, Taste

BANNER = "<!-- Generated by scripts/taste.py build from data/*.json. Never edit by hand. -->"
PRINCIPLE_HEAD = ("ID and scope", "Rule", "Why", "Fix", "Check", "Seen in")
SITE_HEAD = ("Site", "Kind", "Repository", "Taste docs", "Commands")


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def row(cells: tuple[str, ...]) -> str:
    return "| " + " | ".join(cell(text) for text in cells) + " |"


def table(head: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    divider = "| " + " | ".join("---" for _ in head) + " |"
    return [row(head), divider, *map(row, rows)]


def check_cell(refs: tuple[FileRef, ...]) -> str:
    return "<br>".join(f"{ref.site}: `{ref.file}`" for ref in refs) or "Manual walk"


def evidence_cell(refs: tuple[Evidence, ...]) -> str:
    return ", ".join(f"{ref.site} #{ref.pr}" for ref in refs) or "-"


def principle_row(item: Principle) -> tuple[str, ...]:
    return (
        f"`{item.id}`<br>{item.scope.value}",
        item.rule,
        item.why,
        item.fix,
        check_cell(item.checks),
        evidence_cell(item.evidence),
    )


def area_section(area: Area, principles: tuple[Principle, ...]) -> list[str]:
    rows = [principle_row(item) for item in principles if item.area == area.id]
    return [f"## {area.title}", "", area.summary, "", *table(PRINCIPLE_HEAD, rows), ""]


def render_principles(taste: Taste) -> str:
    intro = "Rules that hold for every site. Each site keeps its own choices in its taste doc: see `sites.md`."
    sections = [line for area in taste.areas for line in area_section(area, taste.principles)]
    return "\n".join([BANNER, "", "# Principles", "", intro, "", *sections]).rstrip() + "\n"


def command_cell(site: Site) -> str:
    return "<br>".join(f"`{command.run}`: {command.does}" for command in site.commands)


def docs_cell(site: Site) -> str:
    docs = "<br>".join(f"`{path}`" for path in site.taste_docs) or "None yet"
    return f"{docs}<br>Pending: {site.pending_pr}" if site.pending_pr else docs


def site_row(site: Site) -> tuple[str, ...]:
    link = f"[{site.name}]({site.url})"
    return (link, site.kind.value, f"`{site.repo}`", docs_cell(site), command_cell(site))


def render_sites(taste: Taste) -> str:
    intro = "Where each site keeps its own taste. Run `scripts/taste.py sites` to compare this list with the checkouts."
    rows = [site_row(site) for site in taste.sites]
    return "\n".join([BANNER, "", "# Sites", "", intro, "", *table(SITE_HEAD, rows)]) + "\n"
